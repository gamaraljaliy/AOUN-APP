create table public.categories (
  id integer primary key, name_ar text not null, name_en text not null
);
create table public.places (
  id integer generated by default as identity primary key,
  name_ar text not null, name_en text not null,
  category_id integer not null references public.categories
);
create table public.facilities (
  id smallint primary key check (id between 1 and 9),
  name_ar text not null, name_en text not null
);
create type public.facility_status as enum ('available','unavailable','not_applicable');
create table public.place_facilities (
  place_id integer references public.places on delete cascade,
  facility_id smallint references public.facilities,
  status public.facility_status not null,
  primary key (place_id, facility_id)
);
