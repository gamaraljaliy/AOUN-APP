do $$
declare tbl text;
begin
  foreach tbl in array array['categories','places','facilities','place_facilities'] loop
    execute format('alter table public.%I enable row level security',tbl);
    execute format('revoke all on public.%I from public, anon, authenticated',tbl);
    execute format('grant select on public.%I to anon, authenticated',tbl);
    execute format('create policy public_read on public.%I for select to anon, authenticated using (true)',tbl);
  end loop;
end $$;

create view public.place_summary with (security_invoker = true) as
select p.id, p.name_ar, p.name_en, c.name_ar as category_ar, c.name_en as category_en,
  case when count(s.status) < 9 or count(*) filter (where s.status <> 'not_applicable') = 0 then null
       when 100 * count(*) filter (where s.status = 'available') >=
             70 * count(*) filter (where s.status <> 'not_applicable') then 'accessible'
       when count(*) filter (where s.status = 'available') > 0 then 'partially_accessible'
       else 'not_accessible' end as level
from public.places p join public.categories c on c.id = p.category_id
left join public.place_facilities s on s.place_id = p.id
group by p.id, c.id;
grant select on public.place_summary to anon, authenticated;

create function public.search_places(term text default '', required_ids integer[] default '{}')
returns setof public.place_summary language sql stable security invoker set search_path = '' as $$
select v.* from public.place_summary v
where exists (
  select 1 from unnest(array[v.name_ar,v.name_en,v.category_ar,v.category_en]) t(label)
  where strpos(lower(t.label),lower(trim(term))) > 0
) and not exists (
  select 1 from unnest(required_ids) r(id) where not exists (
    select 1 from public.place_facilities s where s.place_id=v.id and s.facility_id=r.id and s.status='available'
  )
) order by v.id;
$$;

create function public.place_details(target_id integer) returns jsonb
language sql stable security invoker set search_path = '' as $$
select to_jsonb(v) || jsonb_build_object('facilities',(
 select jsonb_agg(jsonb_build_object('id',f.id,'name_ar',f.name_ar,'name_en',f.name_en,'status',s.status) order by f.id)
 from public.facilities f left join public.place_facilities s on s.facility_id=f.id and s.place_id=v.id
)) from public.place_summary v where v.id=target_id;
$$;
revoke all on function public.search_places(text,integer[]), public.place_details(integer) from public;
grant execute on function public.search_places(text,integer[]), public.place_details(integer) to anon, authenticated;
